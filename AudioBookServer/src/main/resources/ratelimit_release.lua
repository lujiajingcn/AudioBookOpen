-- Rate Limit Release Lua Script
--
-- 用途：把一次「已占用」的配额还回去。
--
-- 背景：固定窗口计数器原先按「请求次数」计——成功登录同样吃掉一次配额，
-- 于是用户连错几次密码、或一分钟内反复登录/登出切换账号就会撞 429
-- 「登录请求过于频繁」，而密码本身是对的。登录/注册的配额语义应该是
-- 【失败次数】：只有失败才计数，成功应当退还本次占用。
--
-- KEYS[1] = 限流 key（如 "rate_limit:login:192.168.1.1"）
-- 返回 1 表示已退还，0 表示无可退还（键不存在，或计数已为 0）
--
-- ⚠️ 三条不能改坏的约束：
--   1) 键不存在时直接返回 0，**不做反向补记**。若在这里 DECR 出一个新键，
--      会因为 Redis 把不存在的键当作 0 而得到 -1，凭空建出负数计数键，
--      之后每次 INCR 都要先把这个负数填平，窗口计数被永久打偏。
--   2) DECR 不会触碰 TTL，**不要改成「减到 0 就 DEL」**。删键后下一个请求
--      INCR 得到 1 并重新 EXPIRE，等于把窗口起点往后推——攻击者在失败次数
--      用满前穿插一次成功登录，就能无限延长窗口、彻底绕过暴力破解限流。
--      保留「值为 0、TTL 仍是原来的」这个状态才是正确的。
--   3) GET + DECR 必须留在同一个脚本里保持原子性：拆成两次调用会出现
--      「读到时 > 0、真正减之前窗口已过期」的竞态。

local key = KEYS[1]

local current = redis.call('GET', key)
if not current then
    return 0
end

local n = tonumber(current)
if not n or n <= 0 then
    return 0
end

redis.call('DECR', key)

return 1
