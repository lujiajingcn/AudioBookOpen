package com.audiobook.audiobookplayer

/**
 * 书架任务状态文字（书籍名下方的合成状态）的**可点击性**判定（唯一真源）。
 *
 * ## 需求
 *
 * 书架上每本书的下方挂着它的合成任务行，行的第一列是状态文字
 * （「已完成」「合成中」「失败」「排队中」…）。用户诉求：
 *
 * - 点**书名** → 进阅读页（原有行为，不变）；
 * - 点**状态文字** → 合成已结束时也能进阅读页，合成没结束时**点了不响应**。
 *
 * 「不响应」比「给个 Toast」好：合成中的书本来就没有可读内容，
 * 弹一句「合成完成后才能阅读」等于把同一个结论说三遍（状态文字本身就写着
 * 「合成中」），还打断用户。什么都不发生 = 界面自洽。
 *
 * ## 规则
 *
 * | 合成状态 | 状态文字可点 | 说明 |
 * |---|---|---|
 * | completed | 是 | 合成结束，音频可听 |
 * | partial | 是 | 部分完成，过程已停，可听已合成的部分 |
 * | failed | 是 | 过程已停（有电子书时仍可进阅读器看正文） |
 * | processing / queued / pending | 否 | 还在跑，进阅读页没意义 |
 * | 未知状态 | 否 | 保守：宁可不可点，也不把「还在合成」误判成「已结束」 |
 * | 下载中 / 下载失败 | 否 | 见下 |
 *
 * ⚠️ **下载态一律不可点**：下载是另一件事（把服务端音频拉到本地）。
 * `downloadStatus` 非空时，状态文字显示的是「下载中」「下载失败」——
 * 那是**下载进度**的结论，不是**合成**的结论。合成确实结束了，
 * 但这一行此刻讲的不是合成，点它期望的是看下载情况而不是被带进阅读页
 * （那时本地音频还没下齐，进去也是断的）。所以这里以**显示出来的文字**为准。
 *
 * ## 为什么抽成纯函数
 *
 * 这条判定会被 View 复用路径反复穿过（`bindTasks` 复用子 View，任务数不变时
 * 不重新 inflate），一旦漏写某个分支就会把**上一条任务的可点性串到下一条**——
 * 不崩溃、不闪烁、lint 也过，代码审查看不出来。抽成纯函数后用矩阵钉死。
 */
internal fun isSynthesisFinished(
    status: String,
    downloadStatus: String?
): Boolean {
    // 下载态覆盖了状态文字（显示「下载中」「下载失败」），此时不是合成结论
    if (downloadStatus == "downloading" || downloadStatus == "failed") return false
    return status == "completed" || status == "partial" || status == "failed"
}
